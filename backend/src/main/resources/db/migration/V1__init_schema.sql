-- JPM HRMS - initial schema (PostgreSQL 14+; also runs on H2 in PostgreSQL mode for local development)

CREATE TABLE app_users (
    id                      BIGINT       GENERATED BY DEFAULT AS IDENTITY,
    username                VARCHAR(100) NOT NULL,
    full_name               VARCHAR(150) NOT NULL,
    email                   VARCHAR(200),
    password_hash           VARCHAR(100) NOT NULL,
    role                    VARCHAR(20)  NOT NULL,
    enabled                 BOOLEAN      NOT NULL DEFAULT TRUE,
    notifications_seen_at   TIMESTAMP(6) WITH TIME ZONE NULL,
    last_login_at           TIMESTAMP(6) WITH TIME ZONE NULL,
    created_at              TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at              TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT uk_users_username UNIQUE (username)
);

CREATE TABLE departments (
    id          BIGINT       GENERATED BY DEFAULT AS IDENTITY,
    name        VARCHAR(100) NOT NULL,
    description VARCHAR(500),
    active      BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at  TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at  TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT uk_departments_name UNIQUE (name)
);

CREATE TABLE candidates (
    id                    BIGINT        GENERATED BY DEFAULT AS IDENTITY,
    candidate_code        VARCHAR(30),
    full_name             VARCHAR(150)  NOT NULL,
    date_of_birth         DATE,
    mobile                VARCHAR(20),
    email                 VARCHAR(200),
    address               VARCHAR(1000),
    qualification         VARCHAR(200),
    institution           VARCHAR(200),
    passing_year          INT,
    previous_company      VARCHAR(200),
    experience_years      DECIMAL(4,1),
    previous_designation  VARCHAR(150),
    skills                VARCHAR(2000),
    expected_salary       VARCHAR(100),
    department_id         BIGINT,
    department_raw        VARCHAR(150),
    application_date      DATE          NOT NULL,
    applied_at            TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    application_status    VARCHAR(20)   NOT NULL,
    interview_status      VARCHAR(20)   NOT NULL,
    verification_status   VARCHAR(20)   NOT NULL,
    reference_name        VARCHAR(150),
    reference_relation    VARCHAR(150),
    reference_contact     VARCHAR(200),
    source                VARCHAR(20)   NOT NULL,
    source_row_key        VARCHAR(64),
    data_issues           VARCHAR(2000),
    version               BIGINT        NOT NULL DEFAULT 0,
    created_at            TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at            TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT uk_candidates_code UNIQUE (candidate_code),
    CONSTRAINT uk_candidates_source_row UNIQUE (source_row_key),
    CONSTRAINT fk_candidates_department FOREIGN KEY (department_id) REFERENCES departments (id)
);

CREATE INDEX idx_candidates_name ON candidates (full_name);
CREATE INDEX idx_candidates_email ON candidates (email);
CREATE INDEX idx_candidates_mobile ON candidates (mobile);
CREATE INDEX idx_candidates_app_date ON candidates (application_date);
CREATE INDEX idx_candidates_app_status ON candidates (application_status);

CREATE TABLE candidate_documents (
    id              BIGINT        GENERATED BY DEFAULT AS IDENTITY,
    candidate_id    BIGINT        NOT NULL,
    doc_type        VARCHAR(20)   NOT NULL,
    storage         VARCHAR(10)   NOT NULL,
    file_name       VARCHAR(255),
    content_type    VARCHAR(150),
    size_bytes      BIGINT,
    storage_ref     VARCHAR(500)  NOT NULL,
    uploaded_by     VARCHAR(100),
    created_at      TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT fk_documents_candidate FOREIGN KEY (candidate_id) REFERENCES candidates (id) ON DELETE CASCADE
);

CREATE INDEX idx_documents_candidate ON candidate_documents (candidate_id);

CREATE TABLE hr_remarks (
    id            BIGINT        GENERATED BY DEFAULT AS IDENTITY,
    candidate_id  BIGINT        NOT NULL,
    author        VARCHAR(150)  NOT NULL,
    remark        VARCHAR(2000) NOT NULL,
    created_at    TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT fk_remarks_candidate FOREIGN KEY (candidate_id) REFERENCES candidates (id) ON DELETE CASCADE
);

CREATE INDEX idx_remarks_candidate ON hr_remarks (candidate_id);

CREATE TABLE interviews (
    id                BIGINT        GENERATED BY DEFAULT AS IDENTITY,
    candidate_id      BIGINT        NOT NULL,
    scheduled_at      TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    duration_minutes  INT           NOT NULL,
    round_name        VARCHAR(100)  NOT NULL,
    interviewer       VARCHAR(150)  NOT NULL,
    mode              VARCHAR(20)   NOT NULL,
    location          VARCHAR(300),
    status            VARCHAR(20)   NOT NULL,
    remarks           VARCHAR(2000),
    created_by        VARCHAR(100),
    version           BIGINT        NOT NULL DEFAULT 0,
    created_at        TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at        TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT fk_interviews_candidate FOREIGN KEY (candidate_id) REFERENCES candidates (id) ON DELETE CASCADE
);

CREATE INDEX idx_interviews_scheduled ON interviews (scheduled_at);
CREATE INDEX idx_interviews_candidate ON interviews (candidate_id);

CREATE TABLE audit_logs (
    id           BIGINT        GENERATED BY DEFAULT AS IDENTITY,
    occurred_at  TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    actor        VARCHAR(100)  NOT NULL,
    action       VARCHAR(50)   NOT NULL,
    entity_type  VARCHAR(30),
    entity_id    BIGINT,
    details      VARCHAR(2000),
    PRIMARY KEY (id)
);

CREATE INDEX idx_audit_entity ON audit_logs (entity_type, entity_id);
CREATE INDEX idx_audit_time ON audit_logs (occurred_at);

-- Single-row table: admin-editable Google Sheets integration settings.
-- Credentials are NEVER stored here; they come from the server environment.
CREATE TABLE integration_settings (
    id                     BIGINT        NOT NULL,
    spreadsheet_id         VARCHAR(200),
    sheet_range            VARCHAR(200),
    form_url               VARCHAR(500),
    auto_sync_enabled      BOOLEAN       NOT NULL DEFAULT FALSE,
    sync_interval_minutes  INT           NOT NULL DEFAULT 15,
    column_mapping         VARCHAR(4000),
    updated_by             VARCHAR(100),
    updated_at             TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    PRIMARY KEY (id)
);

CREATE TABLE sync_runs (
    id                BIGINT        GENERATED BY DEFAULT AS IDENTITY,
    started_at        TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    finished_at       TIMESTAMP(6) WITH TIME ZONE,
    triggered_by      VARCHAR(100)  NOT NULL,
    status            VARCHAR(20)   NOT NULL,
    rows_read         INT           NOT NULL DEFAULT 0,
    created_count     INT           NOT NULL DEFAULT 0,
    duplicate_count   INT           NOT NULL DEFAULT 0,
    skipped_count     INT           NOT NULL DEFAULT 0,
    warning_count     INT           NOT NULL DEFAULT 0,
    messages          TEXT,
    error_message     VARCHAR(2000),
    PRIMARY KEY (id)
);

CREATE INDEX idx_sync_runs_started ON sync_runs (started_at);

-- Sheet rows that were skipped (duplicate / invalid) and already reported once.
-- If the row is corrected in the sheet its key changes and it is evaluated again.
CREATE TABLE sync_ignored_rows (
    row_key        VARCHAR(64)   NOT NULL,
    reason         VARCHAR(500)  NOT NULL,
    first_seen_at  TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    PRIMARY KEY (row_key)
);
