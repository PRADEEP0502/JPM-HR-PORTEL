-- Candidate communication module: approved templates, settings and an immutable communication log.

-- Single row: company identity used in every template (admin-managed).
CREATE TABLE communication_settings (
    id                    BIGINT        NOT NULL,
    company_name          VARCHAR(150)  NOT NULL,
    default_venue         VARCHAR(300)  NOT NULL,
    hr_signature          VARCHAR(500)  NOT NULL,
    default_country_code  VARCHAR(4)    NOT NULL,
    updated_by            VARCHAR(100),
    updated_at            TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    PRIMARY KEY (id)
);

-- Versioned templates. A change never edits a row: it inserts a new version and
-- deactivates the old one, so sent communications keep pointing at the exact wording used.
CREATE TABLE message_templates (
    id          BIGINT        GENERATED BY DEFAULT AS IDENTITY,
    channel     VARCHAR(20)   NOT NULL,
    version     INT           NOT NULL,
    subject     VARCHAR(300),
    body        TEXT          NOT NULL,
    active      BOOLEAN       NOT NULL DEFAULT FALSE,
    created_by  VARCHAR(100)  NOT NULL,
    created_at  TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT uk_templates_channel_version UNIQUE (channel, version)
);

-- Every call / WhatsApp / email action. Recipient, name and content are snapshots taken at the
-- time of the action, so history is preserved when candidate details or templates change.
-- No ON DELETE CASCADE: a candidate with communication history cannot be silently deleted.
CREATE TABLE communications (
    id                   BIGINT         GENERATED BY DEFAULT AS IDENTITY,
    candidate_id         BIGINT         NOT NULL,
    interview_id         BIGINT,
    channel              VARCHAR(20)    NOT NULL,
    recipient            VARCHAR(200)   NOT NULL,
    candidate_name       VARCHAR(150)   NOT NULL,
    template_id          BIGINT,
    template_version     INT,
    subject              VARCHAR(300),
    content              TEXT,
    status               VARCHAR(30)    NOT NULL,
    provider             VARCHAR(50),
    provider_message_id  VARCHAR(300),
    error_message        VARCHAR(1000),
    call_outcome         VARCHAR(30),
    notes                VARCHAR(1000),
    retry_of_id          BIGINT,
    initiated_by         VARCHAR(100)   NOT NULL,
    created_at           TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at           TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT fk_comm_candidate FOREIGN KEY (candidate_id) REFERENCES candidates (id),
    CONSTRAINT fk_comm_interview FOREIGN KEY (interview_id) REFERENCES interviews (id) ON DELETE SET NULL,
    CONSTRAINT fk_comm_template FOREIGN KEY (template_id) REFERENCES message_templates (id),
    CONSTRAINT fk_comm_retry FOREIGN KEY (retry_of_id) REFERENCES communications (id)
);

CREATE INDEX idx_comm_candidate ON communications (candidate_id, created_at);
CREATE INDEX idx_comm_interview ON communications (interview_id);
